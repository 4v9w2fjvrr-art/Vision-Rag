from pathlib import Path
import json

import torch
from PIL import Image
from transformers import (
    AutoProcessor,
    AutoModelForMultimodalLM,
)


# ============================================================
# CONFIG
# ============================================================

IMAGE_PATH = Path(
    "data/images/alexander-lunyov-nlY-pr6Fr1w-unsplash.jpg"
)

SCENE_JSON_PATH = Path(
    "outputs/lab11/merged_scene.json"
)

MODEL_ID = "Qwen/Qwen3-VL-2B-Instruct"

OUTPUT_DIR = Path("outputs/lab13")
OUTPUT_DIR.mkdir(
    parents=True,
    exist_ok=True
)

OUTPUT_FILE = OUTPUT_DIR / "grounded_scene_summary.txt"


# ============================================================
# CHECK FILES
# ============================================================

if not IMAGE_PATH.exists():
    raise FileNotFoundError(
        f"Image not found: {IMAGE_PATH}"
    )

if not SCENE_JSON_PATH.exists():
    raise FileNotFoundError(
        f"Scene JSON not found: {SCENE_JSON_PATH}"
    )


# ============================================================
# DEVICE
# ============================================================

device = (
    "mps"
    if torch.backends.mps.is_available()
    else "cpu"
)

print("Device:", device)


# ============================================================
# LOAD IMAGE
# ============================================================

print("Loading image...")

image = Image.open(
    IMAGE_PATH
).convert("RGB")


# ============================================================
# LOAD STRUCTURED SCENE
# ============================================================

print("Loading structured scene evidence...")

with open(
    SCENE_JSON_PATH,
    "r",
    encoding="utf-8"
) as file:

    scene = json.load(file)


# ============================================================
# BUILD CLEAN EVIDENCE
# ============================================================

objects = scene.get(
    "objects",
    []
)

texts = scene.get(
    "texts",
    []
)


object_evidence = []

for obj in objects:

    object_evidence.append(
        {
            "id": obj["object_id"],
            "label": obj["label"],
            "confidence": obj["confidence"],
            "sources": obj["sources"],
            "bounding_box": obj["bounding_box"],
        }
    )


text_evidence = []

for text in texts:

    text_evidence.append(
        {
            "id": text["text_id"],
            "text": text["text"],
            "confidence": text["confidence"],
            "bounding_box": text["bounding_box"],
        }
    )


# ============================================================
# CONVERT EVIDENCE TO TEXT
# ============================================================

evidence = {
    "detected_objects": object_evidence,
    "detected_text": text_evidence,
}

evidence_text = json.dumps(
    evidence,
    indent=2,
    ensure_ascii=False
)


# ============================================================
# LOAD VLM
# ============================================================

print("Loading Qwen3-VL processor...")

processor = AutoProcessor.from_pretrained(
    MODEL_ID
)

print("Loading Qwen3-VL model...")

model = (
    AutoModelForMultimodalLM
    .from_pretrained(
        MODEL_ID,
        torch_dtype="auto",
    )
)

model = model.to(
    device
)

model.eval()


# ============================================================
# GROUNDED PROMPT
# ============================================================

prompt = f"""
You are analysing one street image.

You are given:

1. The original image.
2. Structured detections generated by object detection,
   open-vocabulary detection and OCR systems.

STRUCTURED EVIDENCE:

{evidence_text}


Your task:

1. Examine the original image yourself.
2. Use the structured evidence as supporting evidence.
3. Explain the main objects visible.
4. Explain what the people appear to be doing.
5. Explain important relationships between people, vehicles,
   signs, barriers, trees and houses.
6. Associate OCR text with an object only when the image
   supports that relationship.
7. Mention visible colors only when you can clearly see them.
8. Do not repeatedly list the same object.
9. Do not invent objects just because they appear in the
   structured evidence.
10. If structured evidence looks like a duplicate detection,
    describe the physical object only once.
11. If you are uncertain, say "appears to" or "possibly".
12. Finish with one short overall scene summary.

Keep the response concise.
"""


# ============================================================
# MULTIMODAL MESSAGE
# ============================================================

messages = [
    {
        "role": "user",
        "content": [
            {
                "type": "image",
                "image": image,
            },
            {
                "type": "text",
                "text": prompt,
            },
        ],
    }
]


# ============================================================
# PREPARE INPUT
# ============================================================

print("Preparing grounded multimodal input...")

inputs = processor.apply_chat_template(
    messages,
    add_generation_prompt=True,
    tokenize=True,
    return_dict=True,
    return_tensors="pt",
)


inputs = {
    key: value.to(device)
    if hasattr(value, "to")
    else value

    for key, value in inputs.items()
}


# ============================================================
# GENERATE
# ============================================================

print("Running grounded VLM reasoning...")

with torch.no_grad():

    generated_ids = model.generate(
        **inputs,
        max_new_tokens=250,
        do_sample=False,
        repetition_penalty=1.15,
    )


# ============================================================
# REMOVE ORIGINAL INPUT TOKENS
# ============================================================

input_length = inputs[
    "input_ids"
].shape[-1]

generated_only = generated_ids[
    :,
    input_length:
]


# ============================================================
# DECODE
# ============================================================

answer = processor.batch_decode(
    generated_only,
    skip_special_tokens=True,
)[0]


# ============================================================
# PRINT
# ============================================================

print("\n======================================")
print("GROUNDED VLM SCENE UNDERSTANDING")
print("======================================")

print(answer)


# ============================================================
# SAVE
# ============================================================

with open(
    OUTPUT_FILE,
    "w",
    encoding="utf-8"
) as file:

    file.write(answer)


print("\nSaved:")
print(OUTPUT_FILE)
